#include "services/netscape_cookies.h"

#include <QDateTime>
#include <QDir>
#include <QTemporaryFile>

using namespace Qt::StringLiterals;

namespace red::services {

bool isYouTubeSessionCookie(const QNetworkCookie& cookie)
{
    QString domain = cookie.domain().toLower();
    if (domain.startsWith(u'.')) {
        domain.remove(0, 1);
    }
    for (const auto& suffix :
         {u"youtube.com"_s, u"google.com"_s, u"googlevideo.com"_s, u"youtube-nocookie.com"_s}) {
        if (domain == suffix || domain.endsWith(u'.' + suffix)) {
            return true;
        }
    }
    return false;
}

QString netscapeCookieText(const QList<QNetworkCookie>& cookies)
{
    QString text = u"# Netscape HTTP Cookie File\n# Generated by Red for yt-dlp. Do not edit.\n\n"_s;
    for (const QNetworkCookie& c : cookies) {
        const QString domain = c.domain();
        const bool includeSubdomains = domain.startsWith(u'.');
        const QString path = c.path().isEmpty() ? u"/"_s : c.path();
        const qint64 expires = c.isSessionCookie() ? 0 : c.expirationDate().toSecsSinceEpoch();
        // Session cookies get a far-future expiry: yt-dlp drops expiry-0 rows otherwise.
        const qint64 expiry = expires > 0 ? expires : QDateTime::currentSecsSinceEpoch() + 86400 * 30;
        const QString prefix = c.isHttpOnly() ? u"#HttpOnly_"_s : QString();
        text += prefix + domain + u'\t' + (includeSubdomains ? u"TRUE"_s : u"FALSE"_s) + u'\t' + path +
                u'\t' + (c.isSecure() ? u"TRUE"_s : u"FALSE"_s) + u'\t' + QString::number(expiry) + u'\t' +
                QString::fromUtf8(c.name()) + u'\t' + QString::fromUtf8(c.value()) + u'\n';
    }
    return text;
}

std::unique_ptr<QTemporaryFile> writeCookiesTempFile(const QList<QNetworkCookie>& cookies)
{
    if (cookies.isEmpty()) {
        return nullptr;
    }
    auto file = std::make_unique<QTemporaryFile>(QDir::temp().filePath(u"red-cookies-XXXXXX.txt"_s));
    if (!file->open()) {
        return nullptr;
    }
    file->setPermissions(QFile::ReadOwner | QFile::WriteOwner);
    file->write(netscapeCookieText(cookies).toUtf8());
    file->flush();
    return file;
}

} // namespace red::services
